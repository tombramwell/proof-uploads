"use client";

import { useState, useEffect } from "react";

export default function ProofUploader() {
  const [file, setFile] = useState(null);
  const [passcode, setPasscode] = useState("");
  // NEW: State for the custom fields
  const [arf, setArf] = useState("");
  const [proofNumber, setProofNumber] = useState("");
  
  const [isLoading, setIsLoading] = useState(false);
  const [shareUrl, setShareUrl] = useState("");
  const [error, setError] = useState("");

  useEffect(() => {
    const savedPasscode = localStorage.getItem("proofPasscode");
    if (savedPasscode) {
      setPasscode(savedPasscode);
    }
  }, []);

  const handleFileChange = (e) => {
    const selectedFile = e.target.files[0];
    if (selectedFile) {
      const fileName = selectedFile.name.toLowerCase();
      if (fileName.endsWith('.html') || fileName.endsWith('.htm')) {
        setFile(selectedFile);
        setError("");
        setShareUrl(""); 
      } else {
        setFile(null);
        setError("Please select a valid .html file generated by SingleFile.");
      }
    }
  };

  const handleUpload = async (e) => {
    e.preventDefault();
    if (!file) return;

    setIsLoading(true);
    setError("");

    const formData = new FormData();
    formData.append("file", file);
    formData.append("passcode", passcode);
    // NEW: Append the custom fields to the payload
    formData.append("arf", arf);
    formData.append("proofNumber", proofNumber);

    try {
      const response = await fetch("/api/upload", {
        method: "POST",
        body: formData, 
      });

      const data = await response.json();

      if (!response.ok) throw new Error(data.error || "Upload failed");

      try {
        localStorage.setItem("proofPasscode", passcode);
      } catch (storageError) {
        console.warn("Could not save passcode to browser:", storageError);
      }

      const baseUrl = window.location.origin; 
      const viewableUrl = `${baseUrl}/api/view?url=${encodeURIComponent(data.url)}`;
      
      setShareUrl(viewableUrl);
      
      // NEW: Optional - clear the ARF and Proof fields for the next upload
      setArf("");
      setProofNumber("");
      
    } catch (err) {
      setError(err.message);
      try {
        if (err.message === "Incorrect passcode") {
          localStorage.removeItem("proofPasscode");
        }
      } catch (e) {
        // Ignore storage removal errors
      }
    } finally {
      setIsLoading(false);
    }
  };

  return (
    <main className="min-h-screen p-8 flex flex-col items-center justify-center bg-gray-50">
      <div className="max-w-xl w-full bg-white p-8 rounded-lg shadow-md border border-gray-200">
        <h1 className="text-2xl font-bold mb-2 text-gray-800">Host HTML Proof</h1>
        <p className="text-gray-600 mb-6">
          Upload your SingleFile `.html` document to generate a permanent, shareable link.
        </p>

        <form onSubmit={handleUpload} className="space-y-4">
          <div>
            <input
              type="file"
              accept=".html,.htm"
              onChange={handleFileChange}
              className="block w-full text-sm text-gray-500
                file:mr-4 file:py-2 file:px-4
                file:rounded-md file:border-0
                file:text-sm file:font-semibold
                file:bg-blue-50 file:text-blue-700
                hover:file:bg-blue-100 mb-4"
            />
          </div>

          {/* NEW: ARF and Proof Number fields (Side-by-side) */}
          <div className="flex gap-4">
            <div className="w-1/2">
              <label htmlFor="arf" className="block text-sm font-medium text-gray-700 mb-1">
                ARF (Optional)
              </label>
              <input
                type="text"
                id="arf"
                value={arf}
                onChange={(e) => setArf(e.target.value)}
                placeholder="e.g. 12345"
                className="w-full px-4 py-2 border border-gray-300 rounded-md focus:ring-blue-500 focus:border-blue-500"
              />
            </div>
            <div className="w-1/2">
              <label htmlFor="proofNumber" className="block text-sm font-medium text-gray-700 mb-1">
                Proof Number (Optional)
              </label>
              <input
                type="text"
                id="proofNumber"
                value={proofNumber}
                onChange={(e) => setProofNumber(e.target.value)}
                placeholder="e.g. 1"
                className="w-full px-4 py-2 border border-gray-300 rounded-md focus:ring-blue-500 focus:border-blue-500"
              />
            </div>
          </div>

          <div>
            <label htmlFor="passcode" className="block text-sm font-medium text-gray-700 mb-1">
              Team Passcode
            </label>
            <input
              type="password"
              id="passcode"
              value={passcode}
              onChange={(e) => setPasscode(e.target.value)}
              placeholder="Enter access code"
              required
              className="w-full px-4 py-2 border border-gray-300 rounded-md focus:ring-blue-500 focus:border-blue-500"
            />
          </div>

          {error && <div className="text-red-600 text-sm p-2 bg-red-50 rounded">{error}</div>}

          <button
            type="submit"
            disabled={!file || !passcode || isLoading}
            className={`w-full py-2 px-4 rounded-md text-white font-medium transition-colors 
              ${(!file || !passcode || isLoading) ? 'bg-gray-400 cursor-not-allowed' : 'bg-blue-600 hover:bg-blue-700'}`
            }
          >
            {isLoading ? "Uploading..." : "Get Shareable Link"}
          </button>
        </form>

        {shareUrl && (
          <div className="mt-6 p-4 bg-green-50 border border-green-200 rounded-md">
            <p className="text-sm text-green-800 font-medium mb-2">Upload successful! Share this link:</p>
            <a 
              href={shareUrl} 
              target="_blank" 
              rel="noopener noreferrer"
              className="text-blue-600 underline break-all text-sm"
            >
              {shareUrl}
            </a>
          </div>
        )}
      </div>
    </main>
  );
}